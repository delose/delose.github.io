/* Pulls the real quizzes out of the GeoGain database and writes tools/quizzes.json,
   which is the snapshot this repo builds its answer pages from.

   GeoGain is a SEPARATE repo on the same machine. This repo deliberately keeps a
   committed snapshot rather than reading the DB at build time, so the site can be
   built and deployed from anywhere (CI included) without GeoGain present.

   Re-run whenever GeoGain's quizzes change:
     npm run quiz:import && npm run quiz:build

   Override the DB location with GEOGAIN_DB=/path/to/geogain.db                */
import { writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const DB = process.env.GEOGAIN_DB
  || '/Users/eugenedelossantos/prototype/GeoGain/db/geogain.db';
const OUT = new URL('./quizzes.json', import.meta.url);

if (!existsSync(DB)) {
  console.error(`GeoGain database not found at:\n  ${DB}\n\n` +
    `This repo builds from the committed snapshot in tools/quizzes.json, so the\n` +
    `site still builds without it. Set GEOGAIN_DB to re-import.`);
  process.exit(1);
}

const rows = JSON.parse(execFileSync('sqlite3', ['-json', DB,
  `SELECT id, reddit_title, script_json, youtube_url, tiktok_url
     FROM content_queue WHERE niche='spanish' ORDER BY created_at, id;`],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }) || '[]');

/* A slug is a permanent public URL and must never give the answer away. Almost
   every lesson title is safe, but a few ARE the answer ("Me gustaría", whose quiz
   answer is "Me gustaría la cuenta"). Override those by GeoGain id — the build
   fails loudly if a new one appears, so this list stays honest.              */
const SLUG_OVERRIDES = {
  'd4d4b156-c16e-4cd2-8c95-25cf5f0d636f': 'pedir-con-cortesia',  // topic "Me gustaría" is the answer
};

const slugify = (t) => String(t).toLowerCase().normalize('NFD')
  .replace(/[̀-ͯ]/g, '')          // strip accents: they percent-encode into noise
  .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);

const quizzes = [];
const seen = new Map();
const skipped = [];

rows.forEach((r, i) => {
  let s;
  try { s = JSON.parse(r.script_json || '{}'); } catch { s = {}; }
  const q = s.quiz;
  if (!q?.question || !Array.isArray(q.options) || q.options.length < 2) {
    skipped.push(`${r.id.slice(0, 8)} (no usable quiz)`); return;
  }
  const idx = Number.isInteger(q.answerIndex) ? q.answerIndex : -1;
  if (idx < 0 || idx >= q.options.length) {
    skipped.push(`${r.id.slice(0, 8)} (answerIndex ${q.answerIndex} out of range)`); return;
  }

  const topic = (s.lessonTitle || r.reddit_title || '').trim();
  let slug = SLUG_OVERRIDES[r.id] || slugify(topic) || `quiz-${i + 1}`;
  if (seen.has(slug)) {                      // a slug is a permanent public URL: never collide
    const n = seen.get(slug) + 1; seen.set(slug, n); slug = `${slug}-${n}`;
  } else seen.set(slug, 1);

  quizzes.push({
    order: quizzes.length + 1,
    id: r.id,                                // join key back to GeoGain's content_queue
    slug,
    topic,
    question: q.question.trim(),
    options: q.options.map((o) => String(o).trim()),
    answerIndex: idx,
    answer: String(q.options[idx]).trim(),
    why: (q.explanation || '').trim(),
  });
});

await writeFile(OUT, JSON.stringify({
  _comment: 'GENERATED by tools/import-from-geogain.mjs from the GeoGain content_queue. ' +
            'Do not hand-edit — edit the quiz in GeoGain and re-import. ' +
            'Run: npm run quiz:import && npm run quiz:build',
  source: 'GeoGain content_queue, niche=spanish',
  imported: new Date().toISOString().slice(0, 10),
  quizzes,
}, null, 2) + '\n');

console.log(`imported ${quizzes.length} quizzes -> tools/quizzes.json`);
if (skipped.length) console.log(`skipped ${skipped.length}: ${skipped.join(', ')}`);
